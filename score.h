// ============================================================================
//  score.h  -  樂譜：半音階（評測用）＋ 卡農（試聽用）
//
//  兩份譜是兩種用途，不要互相取代：
//
//    半音階  每個音獨立、不重疊，tools/evaluate.py 才切得開來逐音比對。
//            所有評測數字都是從這份譜來的，預設模式永遠是它。
//    卡農    三聲部同時發聲，用來聽「這個音色拿來演奏音樂像不像」。
//            逐音比對對它沒有意義，它的用途就是耳朵。
//
//  卡農原本被整個移除（舊碼在 舊版備份/score_canon.cpp），現在接回來，
//  差別是音高不再寫死：整體會依音色庫實際涵蓋的音域逐聲部做八度安置，
//  見 score.cpp 的說明。
//
//  tick 解析度 = 16 分音符（TC_TICKS_PER_BEAT = 4）
// ============================================================================
#pragma once

#include <Arduino.h>
#include "config.h"

struct ScoreNote {
  uint16_t tick;      // 起始 tick
  uint16_t dur;       // 長度 tick
  uint8_t  midi;
  uint8_t  vel;       // 0..127
  uint8_t  part;      // 0=旋律 1=內聲部 2=低音
};

// ---------------------------------------------------------------------------
//  要產生哪一份譜
//
//  預設一定是半音階：evaluate.py、bench.py、score_test 全部建立在它上面，
//  任何「開機後預設變成別的譜」的改動都會讓既有評測基準悄悄失效。
//  卡農是明確要求（序列埠 j / 選單 Canon）才會切過去，演奏完不會自己留著 ——
//  由呼叫端負責切回來。
// ---------------------------------------------------------------------------
enum ScoreMode : uint8_t {
  TC_SCORE_SCALE = 0,       // 半音階
  TC_SCORE_CANON = 1,       // 卡農
};

void      scoreSetMode(ScoreMode m);
ScoreMode scoreGetMode();

// 產生整份樂譜（回傳音符數量），notes 至少要有 TC_MAX_NOTES 格
int         buildScore(ScoreNote *notes, int maxNotes);
uint16_t    scoreTotalTicks();
const char *scoreName();

// 卡農上一次產生時，每個聲部實際被移了幾個半音（一定是 12 的倍數）。
// part：0 旋律 1 內聲部 2 低音。序列埠會印出來，面板上看不到的東西
// 至少要能在 log 裡查得到，否則「聽起來高了一個八度」無從追起。
int         scoreCanonShift(int part);

// ---------------------------------------------------------------------------
//  半音階的音域
//
//  以前寫死 C3~B4。那個範圍是憑空訂的：音色庫只涵蓋 C4~B4 時，C3 要往下
//  移調 12 個半音，聽起來當然不像 —— 卻會被誤以為是合成器的問題。
//
//  改成由呼叫端指定，實務上就是「音色庫的音域，再往上一個八度」：
//  下半段是內插（音色庫涵蓋得到），上半段是真正在考驗移調與共振峰校正，
//  一次演奏就能聽出兩者的差別。
//
//  不設定的話維持 C3~B4，所以既有的評測流程與 score_test 不受影響。
// ---------------------------------------------------------------------------
void scoreSetScaleRange(int midiLo, int midiHi);
void scoreGetScaleRange(int *midiLo, int *midiHi);

