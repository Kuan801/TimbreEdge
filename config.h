// 攤平後的參數總數 (w1,b1,w2,b2,w3,b3)，Adam 用得到
#define TC_MLP_NPARAM  (TC_MLP_H1 * TC_MLP_IN + TC_MLP_H1 +                  \
                        TC_MLP_H2 * TC_MLP_H1 + TC_MLP_H2 +                  \
                        TC_MLP_OUT * TC_MLP_H2 + TC_MLP_OUT)   // = 2305
